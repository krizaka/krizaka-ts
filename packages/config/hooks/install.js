// Why: every repository gets the same git hooks from a one-line `prepare`, with no hook file of its own (ADR-026).
// What: writes three tiny shims (pre-commit, commit-msg, pre-push) in <git common dir>/krizaka-hooks and points core.hooksPath at
//   them. A shim runs `krizaka-hooks run <hook>` from the repository's node_modules; when the package or node is missing it says so
//   and exits 0, so a contributor without the package can still push (CI is the last word). Idempotent: a second run changes nothing.
//   Not a git repository, or CI: nothing to do.
// How: `installHooks({ cwd, binPath, env })` -> { status: "installed" | "unchanged" | "skipped", reason? }; the bin calls it.
// Owner: platform lane (krizaka-ts, @krizaka/config).
import { spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { isAbsolute, join, resolve } from "node:path";

import { HOOKS } from "./declaration.js";

const PACKAGE_BIN = "node_modules/@krizaka/config/bin/krizaka-hooks.mjs";

/**
 * @param {string} cwd
 * @param {string[]} args
 */
function git(cwd, args) {
  const result = spawnSync("git", args, { cwd, encoding: "utf8" });
  return result.status === 0 ? result.stdout.trim() : null;
}

/**
 * The fallback path baked into the shims: only when this bin is not the one the repository's node_modules holds (npx, a workspace).
 * @param {string} top
 * @param {string} binPath
 */
function fallbackPath(top, binPath) {
  const own = join(top, PACKAGE_BIN);
  try {
    return existsSync(own) && realpathSync(own) === realpathSync(binPath) ? "" : realpathSync(binPath);
  } catch {
    return "";
  }
}

/**
 * @param {string} hook
 * @param {string} fallback
 */
export function shim(hook, fallback) {
  const quoted = "'" + fallback.replaceAll("'", String.raw`'\''`) + "'";
  return [
    "#!/bin/sh",
    "# Generated by `krizaka-hooks install` (@krizaka/config, ADR-026). Do not edit: run the install again.",
    "top=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0",
    `bin="$top/${PACKAGE_BIN}"`,
    fallback ? `[ -f "$bin" ] || bin=${quoted}` : "",
    'if [ ! -f "$bin" ] || ! command -v node >/dev/null 2>&1; then',
    `  echo "krizaka-hooks: @krizaka/config or node is missing, ${hook} skipped (CI is the last word). Install: npx -y -p @krizaka/config krizaka-hooks install" >&2`,
    "  exit 0",
    "fi",
    `exec node "$bin" run ${hook} "$@"`,
    "",
  ]
    .filter((line, i, all) => line !== "" || i === all.length - 1)
    .join("\n");
}

/**
 * @param {{ cwd: string, binPath: string, env?: NodeJS.ProcessEnv }} options
 * @returns {{ status: "installed" | "unchanged" | "skipped", reason?: string }}
 */
export function installHooks({ cwd, binPath, env = process.env }) {
  if (env.CI) return { status: "skipped", reason: "CI: the hooks are for a contributor's clone" };
  const top = git(cwd, ["rev-parse", "--show-toplevel"]);
  const common = git(cwd, ["rev-parse", "--git-common-dir"]);
  if (!top || !common) return { status: "skipped", reason: "not a git repository" };
  const dir = join(isAbsolute(common) ? common : resolve(cwd, common), "krizaka-hooks");
  mkdirSync(dir, { recursive: true });
  const fallback = fallbackPath(top, binPath);
  let changed = false;
  for (const hook of HOOKS) {
    const file = join(dir, hook);
    const wanted = shim(hook, fallback);
    if (!existsSync(file) || readFileSync(file, "utf8") !== wanted) {
      writeFileSync(file, wanted);
      changed = true;
    }
    chmodSync(file, 0o755);
  }
  if (git(cwd, ["config", "--local", "--get", "core.hooksPath"]) !== dir) {
    const set = spawnSync("git", ["config", "--local", "core.hooksPath", dir], { cwd, encoding: "utf8" });
    if (set.status !== 0) return { status: "skipped", reason: `git config failed: ${set.stderr.trim()}` };
    changed = true;
  }
  return { status: changed ? "installed" : "unchanged" };
}
